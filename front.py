# what is virtual environment?

#  => virtual environment is used to create a seperate environment for each python project.
#  => (venv) is a extension for virtual environment .

# why we use virtual environment?

#  => to avoid version conflicts between different projects.
#  => to keep project libraries seperate.
#  => to manage packages indepenedently for each project.

 # example:
 #  => if we have two projects, project A and project B.
 #  => project A requires numpy version 1.18.0 and project B requires numpy version 1.19.0.

# how to create virtual environment?
# to create a txt file.
# txt file inside the write the libraries that we want to install in our virtual environment.


